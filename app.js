// AUDIO MANAGEMENT
function setupAudioListeners() {
    audio.addEventListener('error', (e) => {
        console.error('Audio load error:', e);
    });

    audio.addEventListener('play', () => {
        isPlaying = true;
        if (playIcon) playIcon.src = 'images/pause-icon-removebg-preview.png';
        if (equalizer) equalizer.classList.add('playing');
        if (playlistCover) playlistCover.src = tracks[currentTrackIndex].cover;
        updateInlineIcons();
    });

    audio.addEventListener('pause', () => {
        isPlaying = false;
        if (playIcon) playIcon.src = 'images/play-icon-removebg-preview.png';
        if (equalizer) equalizer.classList.remove('playing');
        if (playlistCover) playlistCover.src = DEFAULT_COVER;
        updateInlineIcons();
    });

    audio.addEventListener('ended', () => {
        completedTracks.add(currentTrackIndex);
        isPlaying = false;
        if (playIcon) playIcon.src = 'images/play-icon-removebg-preview.png';
        if (equalizer) equalizer.classList.remove('playing');
        if (playlistCover) playlistCover.src = DEFAULT_COVER;
        updateInlineIcons();

        if (completedTracks.size === tracks.length) {
            showCompletionModal();
        }
    });

    audio.addEventListener('loadedmetadata', () => {
        if (durationEl) durationEl.textContent = formatTime(audio.duration);
    });

    audio.addEventListener('timeupdate', () => {
        if (!audio.duration) return;
        const progressPercent = (audio.currentTime / audio.duration) * 100;
        if (progressBar) progressBar.style.width = `${progressPercent}%`;
        if (pawHandle) pawHandle.style.left = `${progressPercent}%`;
        if (currentTimeEl) currentTimeEl.textContent = formatTime(audio.currentTime);
    });
}

function loadTrack(index) {
    currentTrackIndex = index;
    const track = tracks[index];

    audio.pause();
    audio.src = track.audioSrc;

    if (playerThumb) playerThumb.src = track.cover;
    if (playerSongName) playerSongName.textContent = track.title;
    if (playerSongArtist) playerSongArtist.textContent = track.artist;

    if (playlistCover && !isPlaying) {
        playlistCover.src = DEFAULT_COVER;
    }

    trackRows.forEach((row, idx) => {
        const icon = row.querySelector('.track-play-icon');
        if (idx === index) {
            row.classList.add('active-track');
            if (icon) icon.src = isPlaying ? 'images/pause-icon-removebg-preview.png' : 'images/play-icon-removebg-preview.png';
        } else {
            row.classList.remove('active-track');
            if (icon) icon.src = 'images/play-icon-removebg-preview.png';
        }
    });
}

function updateInlineIcons() {
    trackRows.forEach((row, idx) => {
        const icon = row.querySelector('.track-play-icon');
        if (idx === currentTrackIndex) {
            if (icon) icon.src = isPlaying ? 'images/pause-icon-removebg-preview.png' : 'images/play-icon-removebg-preview.png';
        } else {
            if (icon) icon.src = 'images/play-icon-removebg-preview.png';
        }
    });
}

function togglePlay() {
    if (isPlaying) {
        audio.pause();
    } else {
        audio.play().catch(err => console.error('Playback error:', err));
    }
}

function formatTime(seconds) {
    if (isNaN(seconds)) return "0:00";
    const mins = Math.floor(seconds / 60);
    const secs = Math.floor(seconds % 60);
    return `${mins}:${secs < 10 ? '0' : ''}${secs}`;
}

// EVENT LISTENERS: PLAYER
if (playBtn) playBtn.addEventListener('click', togglePlay);

trackRows.forEach((row) => {
    row.addEventListener('click', () => {
        const index = parseInt(row.getAttribute('data-track-index'), 10);
        if (index === currentTrackIndex) {
            togglePlay();
        } else {
            loadTrack(index);
            audio.play().catch(err => console.error('Playback error:', err));
        }
    });
});

if (progressBarContainer) {
    progressBarContainer.addEventListener('click', (e) => {
        const rect = progressBarContainer.getBoundingClientRect();
        const clickPosition = (e.clientX - rect.left) / rect.width;
        if (audio.duration) {
            audio.currentTime = clickPosition * audio.duration;
        }
    });
}

